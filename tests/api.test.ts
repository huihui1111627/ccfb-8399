test('manual merge is reversible and affects accuracy', () => {
  const s = demoService();
  const baseF1 = s.evaluateAgainstTruth().entity!.persons.bcubed.f1;
  const res = s.ensureResolved();
  const wang = res.persons.filter(p => p.canonicalName === '王海峰');
  s.mergeEntities([wang[0].id, wang[1].id], '测试合并');
  const after = s.evaluateAgainstTruth();
  assert.ok(after.entity!.persons.bcubed.f1 < baseF1, 'wrong merge must lower the score');
  s.clearManualEdits();
  assert.equal(s.evaluateAgainstTruth().entity!.persons.bcubed.f1, baseF1);
});

test('manual split creates a distinct subject and is reversible', () => {
  const s = demoService();
  const res = s.ensureResolved();
  const target = res.persons.find(p => p.recordIds.length > 5)!;
  const before = res.persons.length;
  const rec = target.recordIds.find(r => r.startsWith('EQ'))!;
  s.splitEntity(target.id, [rec], '拆分测试');
  const after = s.ensureResolved();
  assert.equal(after.persons.length, before + 1);
  assert.ok(after.persons.some(p => p.canonicalName === '拆分测试'));
  s.clearManualEdits();
  assert.equal(s.ensureResolved().persons.length, before);
});

test('history honours effective dates for both shares and relations', () => {
  const s = demoService();
  // In 2019 王海峰(110101…1234) controlled 蓝海; by 2020 STAR invested and the
  // concert/nominee relations were not yet signed.
  const y2019 = s.evaluateOwnership('2019-06-30');
  const y2022 = s.evaluateOwnership('2022-06-30');
  assert.equal(y2019.ownership.activeRelations.length, 0);
  assert.ok(y2022.ownership.activeRelations.length >= 2);
  const blue = s.ensureResolved().companies.find(c => c.aliases.includes('蓝海科技有限公司'))!;
  const c2019 = y2019.analysis.byCompany.get(blue.id)!;
  const c2022 = y2022.analysis.byCompany.get(blue.id)!;
  assert.ok(c2019.pct !== c2022.pct);
  assert.ok(c2019.pct > c2022.pct, 'diluted after bringing in new shareholders');
});

test('a later change row supersedes the earlier cap table entry', () => {
  const s = demoService();
  const res = s.ensureResolved();
  const star = res.companies.find(c => c.canonicalName === '星海控股有限公司')!;
  const early = s.evaluateOwnership('2019-06-30').ownership.direct.get(star.id)!;
  const late = s.evaluateOwnership('2025-12-31').ownership.direct.get(star.id)!;
  // 蓝海网络技术有限公司 was not a shareholder of 星海 in 2019 but is by 2020
  const names = new Map(res.entities.map(e => [e.id, e.canonicalName]));
  const blueId = [...names.entries()].find(([, n]) => n === '蓝海科技有限公司')![0];
  assert.equal(early.has(blueId), false);
  assert.equal(late.has(blueId), true);
});

test('unbalanced cap tables are normalised and reported, never silently trusted', () => {
  const direct = new Map<string, Map<string, number>>([
    ['C', new Map([['A', 2], ['B', 3]])],
  ]);
  const entities = ['C', 'A', 'B'].map(id => ({
    id, kind: (id === 'C' ? 'company' : 'person') as 'company' | 'person', canonicalName: id,
    aliases: [id], uscc: null, addresses: [], legalReps: [], idFragments: [], recordIds: [],
    confidence: 1, evidence: [], createdAt: '',
  }));
  const rows = [
    { companyId: 'C', holderId: 'A', pct: 2, effectiveDate: '2020-01-01', recordId: 'r1', source: '', holderNameRaw: '', companyNameRaw: '' },
    { companyId: 'C', holderId: 'B', pct: 3, effectiveDate: '2020-01-01', recordId: 'r2', source: '', holderNameRaw: '', companyNameRaw: '' },
  ];
  const graph = buildGraph(rows, entities, []);
  assert.equal(graph.diagnostics.unbalancedCompanies.length, 1);
  assert.ok(Math.abs(graph.direct.get('C')!.get('A')! - 0.4) < 1e-9);
  assert.ok(Math.abs(graph.direct.get('C')!.get('B')! - 0.6) < 1e-9);
  void direct;
});

test('eventual 100% ownership through a chain is computed exactly', () => {
  const direct = new Map<string, Map<string, number>>([
    ['TOP', new Map([['MID', 0.8]])],
    ['MID', new Map([['LEAF', 0.5]])],
    ['LEAF', new Map([['P', 1]])],
  ]);
  const sol = solveLinear(['TOP', 'MID', 'LEAF'], direct, { persons: ['P'] });
  // P owns LEAF outright, so it owns 50% of MID through LEAF and 40% of TOP
  assert.ok(Math.abs((sol.matrix.get('P')!.get('TOP') ?? 0) - 0.4) < 1e-9);
  assert.ok(Math.abs((sol.matrix.get('P')!.get('MID') ?? 0) - 0.5) < 1e-9);
  assert.ok(Math.abs((sol.matrix.get('P')!.get('LEAF') ?? 0) - 1) < 1e-9);
});

test('controller can be a dispersed company with no owner above 25%', () => {
  const direct = new Map<string, Map<string, number>>([
    ['C', new Map([['A', 0.2], ['B', 0.2], ['D', 0.2], ['E', 0.2], ['F', 0.2]])],
  ]);
  const entities = ['C', 'A', 'B', 'D', 'E', 'F'].map(id => ({
    id, kind: (id === 'C' ? 'company' : 'person') as 'company' | 'person', canonicalName: id,
    aliases: [id], uscc: null, addresses: [], legalReps: [], idFragments: [], recordIds: [],
    confidence: 1, evidence: [], createdAt: '',
  }));
  const graph = buildGraph([], entities, []);
  graph.companies = ['C'];
  graph.persons = ['A', 'B', 'D', 'E', 'F'];
  graph.direct = direct;
  const ownership = buildOwnershipResult(graph, new Map(entities.map(e => [e.id, e.id])));
  const analysis = analyseControllers(ownership, entities, []);
  const ctrl = analysis.byCompany.get('C')!;
  assert.equal(ctrl.kind, 'none');
  assert.equal(ctrl.beneficialOwners.length, 0);
});

